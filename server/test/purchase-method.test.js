import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import Database from 'better-sqlite3';
import { cleanPurchaseUrl, externalPurchase } from '../src/purchase-method.js';
import { repairTaviPurchase } from '../src/purchase-repair.js';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sf-purchase-'));
Object.assign(process.env, { DATA_DIR: dir, PUBLIC_URL: 'https://shop.example', STRIPE_SECRET_KEY: 'sk_test_fake' });
const { app } = await import('../src/index.js');
const { db } = await import('../src/db.js');
const store = await import('../src/store.js');
const commerce = await import('../src/commerce.js');
const { productPage, storePage } = await import('../src/render.js');
let server, base;
before(async () => { server = app.listen(0); await new Promise(r => server.once('listening', r)); base = `http://127.0.0.1:${server.address().port}`; });
after(() => { server.close(); db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
test('external checkout publishes without Stripe, hides local selling claims, and rejects stale carts', async () => {
 const reg = await (await fetch(base+'/api/sellers', { method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({store_name:'Test Books'}) })).json();
 db.prepare("UPDATE accounts SET plan='pro' WHERE id=?").run(reg.account.id);
 const seller = db.prepare("SELECT * FROM sellers WHERE id=?").get(reg.seller.id);
 let p = store.createProduct(seller, {title:'Coloring book', kind:'physical', price:12, inventory:0, purchase_method:'external', external_url:'https://a.co/d/03F3C84Y'});
 p = await store.publishProduct(seller,p.id);
 const html = productPage(seller,p,'https://shop.example');
 assert.match(html,/href="https:\/\/a.co\/d\/03F3C84Y"[^>]*>Buy on Amazon/);
 for (const pattern of [/id="add"/,/id="now"/,/Secure checkout by Stripe/,/Free shipping/i,/\$12\.00/,/Sold out/]) assert.doesNotMatch(html,pattern);
 assert.doesNotMatch(storePage(seller,[p],'https://shop.example'),/Secure checkout by Stripe|Sold out|\$12\.00/);
 assert.throws(()=>commerce.priceCart(seller,[{product_id:p.id,qty:1}]),/purchased on another website/);
 db.prepare("UPDATE sellers SET stripe_ready=1,stripe_account_id='acct_test' WHERE id=?").run(seller.id);
 const count = db.prepare('SELECT COUNT(*) AS n FROM orders').get().n;
 const response = await fetch(`${base}/s/${seller.store_slug}/checkout`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({items:[{product_id:p.id,qty:1}]})});
 assert.equal(response.status,400); assert.match((await response.json()).error,/purchased on another website/);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM orders').get().n,count);
 assert.throws(()=>store.updateProduct(seller,p.id,{external_url:'javascript:alert(1)'}),/https/);
 assert.equal(store.productRow(seller,p.id).external_url,'https://a.co/d/03F3C84Y');
 assert.throws(()=>store.updateProduct(seller,p.id,{purchase_method:'direct',kind:'digital'}),/attach a download/);
 store.updateProduct(seller,p.id,{purchase_method:'direct',inventory:null});
 assert.doesNotThrow(()=>commerce.priceCart(seller,[{product_id:p.id,qty:1}]));
});
test('purchase links reject unsafe schemes and distinguish Amazon lookalikes', () => {
 for(const url of ['javascript:alert(1)','http://amazon.com','https://user:pass@amazon.com','https://localhost']) assert.throws(()=>cleanPurchaseUrl(url));
 assert.equal(externalPurchase({purchase_method:'external',external_url:'https://amazon.com.evil.example/item'}).label,'Buy on website');
 assert.equal(externalPurchase({purchase_method:'external',external_url:'https://www.amazon.com/dp/book'}).label,'Buy on Amazon');
});
test('Tavi repair changes only the identified listing and is not repeated', () => {
 const d=new Database(':memory:');
 d.exec("CREATE TABLE sellers(id TEXT,store_slug TEXT); CREATE TABLE products(id TEXT,seller_id TEXT,title TEXT,description TEXT,purchase_method TEXT DEFAULT 'direct',external_url TEXT,slug TEXT);");
 d.prepare('INSERT INTO sellers VALUES (?,?)').run('s','my-snapfront-store-6');
 d.prepare('INSERT INTO products(id,seller_id,title,description,slug) VALUES (?,?,?,?,?)').run('p','s','Tavi and Friends: My First Coloring Book','Order: https://a.co/d/03F3C84Y','original-slug');
 repairTaviPurchase(d);let p=d.prepare('SELECT * FROM products').get();assert.equal(p.purchase_method,'external');assert.equal(p.external_url,'https://a.co/d/03F3C84Y');assert.equal(p.slug,'original-slug');assert.equal(p.description,'Order: https://a.co/d/03F3C84Y');
 d.exec("UPDATE products SET purchase_method='direct'");repairTaviPurchase(d);assert.equal(d.prepare('SELECT purchase_method FROM products').get().purchase_method,'direct');d.close();
});
