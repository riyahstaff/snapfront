import { readFile, mkdir, copyFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { PREMIUM_THEMES } from '../../server/src/premium-themes.js';
import { THEMES } from '../../server/src/themes.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = path.join(root, 'assets/theme-previews');
await mkdir(target, { recursive: true });
const entries = [];
for (const theme of PREMIUM_THEMES) {
  if (!theme.preview?.startsWith('/theme-assets/')) throw new Error(`Missing actual preview for ${theme.id}`);
  const filename = path.basename(theme.preview);
  const source = path.join(root, '../server/assets/themes', filename);
  const bytes = await readFile(source);
  if (bytes.length < 100 || bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error(`Invalid WebP preview for ${theme.id}`);
  await copyFile(source, path.join(target, filename));
  entries.push(`  ${JSON.stringify(theme.id)}: require(${JSON.stringify('../../assets/theme-previews/' + filename)}),`);
}
if (entries.length !== 85) throw new Error(`Expected 85 genuine premium previews, got ${entries.length}`);
for (const theme of THEMES.filter(theme => theme.collection !== 'premium')) {
  const filename = `classic-${theme.id}-preview.webp`;
  const bytes = await readFile(path.join(target, filename));
  if (bytes.length < 100 || bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error(`Generate the real classic screenshot first: ${theme.id}`);
  entries.push(`  ${JSON.stringify(theme.id)}: require(${JSON.stringify('../../assets/theme-previews/' + filename)}),`);
}
if (entries.length !== 105) throw new Error(`Expected 105 real previews, got ${entries.length}`);
await writeFile(path.join(root, 'src/lib/bundled-theme-previews.ts'), `// Generated by scripts/package-theme-thumbnails.mjs from the actual storefront renderer previews.\n// Illustrative catalog assets only: never use these as seller product/cover uploads.\nconst previews: Record<string, number> = {\n${entries.join('\n')}\n};\n\nexport function bundledThemePreview(id: string): number | null {\n  return Object.prototype.hasOwnProperty.call(previews, id) ? previews[id] : null;\n}\n`);
console.log(`Packaged ${entries.length} genuine previews (20 classic, 85 premium) with static Metro imports.`);
